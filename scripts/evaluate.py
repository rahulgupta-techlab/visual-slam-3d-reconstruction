#!/usr/bin/env python3
"""Evaluate VO trajectories with evo and generate metrics/plots from actual runs."""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path


def run_metric(command: list[str]) -> tuple[float, str]:
    completed = subprocess.run(command, check=True, text=True, capture_output=True)
    output = completed.stdout + "\n" + completed.stderr
    match = re.search(r"rmse\s+([0-9.eE+-]+)\s*m", output, re.IGNORECASE)
    if not match:
        raise RuntimeError(f"Could not parse RMSE from evo output:\n{output}")
    return float(match.group(1)), output


def evaluate(sequence: str, data_root: Path = Path("data/tum")) -> tuple[float, float]:
    sequence_dir = data_root / sequence
    ground_truth = sequence_dir / "groundtruth.txt"
    estimate = Path("results") / f"{sequence}_estimated.txt"
    if not ground_truth.exists():
        raise FileNotFoundError(f"Missing ground truth: {ground_truth}")
    if not estimate.exists():
        raise FileNotFoundError(f"Missing estimate: {estimate}; run scripts/run_vo.py first")
    Path("docs").mkdir(exist_ok=True)
    Path("results").mkdir(exist_ok=True)

    common = ["--align", "--correct_scale", "--t_max_diff", "0.02"]
    ate_cmd = ["evo_ape", "tum", str(ground_truth), str(estimate), *common,
               "--plot", "--plot_mode", "xy", "--save_plot", f"docs/{sequence}_ate.png"]
    rpe_cmd = ["evo_rpe", "tum", str(ground_truth), str(estimate), *common,
               "--delta", "1", "--delta_unit", "f", "--plot", "--plot_mode", "xy",
               "--save_plot", f"docs/{sequence}_rpe.png"]
    ate, ate_output = run_metric(ate_cmd)
    rpe, rpe_output = run_metric(rpe_cmd)
    (Path("results") / f"{sequence}_ate.log").write_text(ate_output, encoding="utf-8")
    (Path("results") / f"{sequence}_rpe.log").write_text(rpe_output, encoding="utf-8")
    return ate, rpe


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seq", choices=["fr1_xyz", "fr1_desk", "all"], default="all")
    parser.add_argument("--data-root", type=Path, default=Path("data/tum"))
    parser.add_argument("--write-pending", action="store_true", help="write an explicit Not run yet table without running metrics")
    args = parser.parse_args()
    sequences = ["fr1_xyz", "fr1_desk"] if args.seq == "all" else [args.seq]
    if args.write_pending:
        lines = ["# Monocular VO evaluation", "",
                 "Generated by python scripts/evaluate.py --write-pending. No benchmark metrics have been measured yet.",
                 "The evaluation protocol uses one global Sim(3) alignment (--align --correct_scale).",
                 "This is scale-aligned monocular evaluation, not metric-scale odometry.", "",
                 "| Sequence | ATE RMSE (m) | RPE RMSE (m) | Status |", "|---|---:|---:|---|"]
        lines.extend(f"| {seq} | — | — | Not run yet |" for seq in sequences)
        Path("results").mkdir(exist_ok=True)
        Path("results/metrics.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("Wrote pending status table to results/metrics.md")
        return
    rows: list[tuple[str, float, float]] = []
    for sequence in sequences:
        ate, rpe = evaluate(sequence, args.data_root)
        rows.append((sequence, ate, rpe))
        print(f"{sequence}: ATE RMSE={ate:.6f} m, RPE RMSE={rpe:.6f} m")
    lines = ["# Monocular VO evaluation", "",
             "Generated by python scripts/evaluate.py; values are parsed from successful evo runs.",
             "All values use a single global Sim(3) alignment (--align --correct_scale).",
             "This is scale-aligned monocular evaluation, not metric-scale odometry.", "",
             "| Sequence | ATE RMSE (m) | RPE RMSE (m) |", "|---|---:|---:|"]
    lines.extend(f"| {seq} | {ate:.6f} | {rpe:.6f} |" for seq, ate, rpe in rows)
    Path("results/metrics.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()
